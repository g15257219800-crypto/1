def style_header(ws, row, cols):
    for c in range(1, cols + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = center
        cell.border = thin


def style_body(ws, start_row, end_row, cols):
    for r in range(start_row, end_row + 1):
        for c in range(1, cols + 1):
            cell = ws.cell(row=r, column=c)
            cell.font = normal_font
            cell.alignment = center
            cell.border = thin
            if (r - start_row) % 2 == 1:
                if cell.fill.fgColor is None or cell.fill.fgColor.rgb in (None, "00000000"):
                    cell.fill = alt_fill


def autosize(ws, widths):
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w


def write_title(ws, title, cols):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=cols)
    cell = ws.cell(1, 1, title)
    cell.font = title_font
    cell.alignment = Alignment(horizontal="left", vertical="center")
    ws.row_dimensions[1].height = 28


def write_note(ws, row, text, cols):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=cols)
    cell = ws.cell(row, 1, text)
    cell.font = note_font
    cell.alignment = left_align
    cell.fill = warn_fill


def write_table(ws, start_row, headers, rows):
    cols = len(headers)
    for i, h in enumerate(headers, 1):
        ws.cell(start_row, i, h)
    style_header(ws, start_row, cols)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row, 1):
            ws.cell(start_row + 1 + ri, ci, val)
    if rows:
        style_body(ws, start_row + 1, start_row + len(rows), cols)
    return start_row + len(rows)


